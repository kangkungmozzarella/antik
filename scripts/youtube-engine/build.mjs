// Bundles entry.js into a string the app injects into the hidden WebView.
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const here = (path) => fileURLToPath(new URL(path, import.meta.url));

const result = await build({
  entryPoints: [here('./entry.js')],
  bundle: true,
  format: 'iife',
  minify: true,
  target: 'chrome100',
  write: false,
});

const code = result.outputFiles[0].text;
await writeFile(
  here('../../src/common/youtube/engine-script.ts'),
  `// Generated by scripts/youtube-engine/build.mjs from scripts/youtube-engine/entry.js. Do not edit.\nexport const ENGINE_SCRIPT = ${JSON.stringify(code)};\n`,
);
console.log(`engine-script.ts written (${(code.length / 1024).toFixed(1)} KB)`);
